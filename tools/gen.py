import json, cv2, numpy as np, math, os
import sys as _s; SRC_DIR=(_s.argv[1] if len(_s.argv)>1 else 'source-drawings').rstrip('/')+'/'
import pathlib; OUT=str(pathlib.Path(__file__).resolve().parent.parent/'src')
SPECS=['1245-T1','1245-T23','1505-T1','1505-T23','997-1','997-2','997-3']
WALLTH={'T6&7':(105,150)}
def wallmask(src):
    lo,hi=(105,150) if src.startswith('T6') else (70,128)
    im=cv2.imread(SRC_DIR+src+'.jpg.jpeg')[:,:,::-1].astype(int)
    mx=im.max(2); mn=im.min(2)
    m=((mx<=hi)&(mx>=lo)&(mx-mn<=14)).astype(np.uint8)*255
    m=cv2.morphologyEx(m,cv2.MORPH_OPEN,cv2.getStructuringElement(cv2.MORPH_RECT,(6,6)))
    m=cv2.morphologyEx(m,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_RECT,(3,3)))
    return m
def path_of(mask,x0,y0,eps=1.0,minarea=30):
    cs,_=cv2.findContours(mask,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_SIMPLE)
    parts=[]
    for c in cs:
        if abs(cv2.contourArea(c))<minarea: continue
        a=cv2.approxPolyDP(c,eps,True).reshape(-1,2)
        parts.append('M'+' L'.join(f'{x-x0},{y-y0}' for x,y in a)+'Z')
    return ''.join(parts)
def door_geom(d):
    h,c,o=d['h'],d['c'],d['o']; R=math.dist(h,c)
    return h,c,o,R
plans=[]
for name in SPECS:
    s=json.load(open(str(pathlib.Path(__file__).parent/'spec'/f'{name}.json')))
    src=s['src']; x0,y0,x1,y1=s['crop']
    img=cv2.imread(SRC_DIR+src+'.jpg.jpeg')
    w=wallmask(src)
    wc=w[y0:y1,x0:x1]
    walls=path_of(wc,0,0)
    # structural: thick wall blocks (>=20px in both directions)
    thick=cv2.morphologyEx(wc,cv2.MORPH_OPEN,cv2.getStructuringElement(cv2.MORPH_RECT,(19,19)))
    struct=path_of(thick,0,0,1.0,120)
    # --- clean furniture raster: remove text, door swings, arrow
    a=img.astype(int); mx=a.max(2); mn=a.min(2)
    rm=np.zeros(w.shape,np.uint8)
    for r in s['rooms']:
        lx,ly=r['label']
        reg=np.zeros_like(rm); cv2.rectangle(reg,(lx-80,ly-45),(lx+80,ly+45),255,-1)
        if src.endswith('Type-1'): reg[:]=0; cv2.rectangle(reg,(lx-30,ly-80),(lx+30,ly+80),255,-1)
        rm|=((mx<85)&(reg>0)).astype(np.uint8)*255
    band=np.zeros_like(rm)
    for d in s['doors']:
        h,c,o,R=door_geom(d)
        a0=math.degrees(math.atan2(c[1]-h[1],c[0]-h[0])); a1=math.degrees(math.atan2(o[1]-h[1],o[0]-h[0]))
        if a1-a0>180: a1-=360
        if a0-a1>180: a1+=360
        cv2.ellipse(band,tuple(h),(int(R),int(R)),0,min(a0,a1)-12,max(a0,a1)+12,255,22)
    rm|=((mx<175)&(mx-mn<30)&(band>0)).astype(np.uint8)*255
    red=(a[...,2]>150)&(a[...,1]<120)&(a[...,0]<120)
    rm|=red.astype(np.uint8)*255
    rm=cv2.dilate(rm,np.ones((3,3),np.uint8)); rm[w>0]=0
    clean=cv2.inpaint(img,rm,4,cv2.INPAINT_TELEA)
    cv2.imwrite(f'{OUT}/assets/plans/{s["id"]}-furniture.jpg',clean[y0:y1,x0:x1],[cv2.IMWRITE_JPEG_QUALITY,80])
    cv2.imwrite(f'{OUT}/assets/plans/{s["id"]}-source.jpg',img[y0:y1,x0:x1],[cv2.IMWRITE_JPEG_QUALITY,80])
    sh=lambda p:[p[0]-x0,p[1]-y0]
    rooms=[]
    for r in s['rooms']:
        rr={k:v for k,v in r.items() if v is not None}
        rr['poly']=[sh(p) for p in r['poly']]; rr['label']=sh(r['label'])
        if 'dimRect' in r:
            X0,Y0,X1,Y1=r['dimRect']; rw,rh=X1-X0,Y1-Y0
            W,L=r['w'],r['l']
            hz,vt=(W,L) if ((W>=L)==(rw>=rh)) or W==L else (L,W)
            rr['dims']={'rect':[X0-x0,Y0-y0,rw,rh],'horizontal':hz,'vertical':vt}
            del rr['dimRect']
        rooms.append(rr)
    doors=[{**d,'h':sh(d['h']),'c':sh(d['c']),'o':sh(d['o'])} for d in s['doors']]
    wins=[[a_[0]-x0,a_[1]-y0,a_[2]-a_[0],a_[3]-a_[1]] for a_ in s['windows']]
    e=s['entry']
    plans.append(dict(id=s['id'],title=s['title'],config=s['config'],areas=s['areas'],note=s.get('note'),
        width=x1-x0,height=y1-y0,walls=walls,structure=struct,rooms=rooms,doors=doors,windows=wins,
        entry=dict(x=e['x']-x0,y=e['y']-y0,dir=e['dir']),sourceFile=src+'.jpg'))
    print(name,len(walls),len(struct))
ids=[p['id'] for p in plans]
ts=['// AUTO-GENERATED by the plan extraction pipeline – geometry is in source-image pixels (after crop).',
    "import type { PlanData } from './types';"]
for p in plans:
    v=p['id'].replace('-','_')
    ts.append(f"import {v}_furn from '../assets/plans/{p['id']}-furniture.jpg';")
    ts.append(f"import {v}_src from '../assets/plans/{p['id']}-source.jpg';")
ts.append('export const PLANS: PlanData[] = [')
for p in plans:
    v=p['id'].replace('-','_'); q=dict(p); q={k:v_ for k,v_ in q.items() if v_ is not None}
    js=json.dumps(q,indent=1)
    js=js[:-2]+f',\n "furnitureImage": {v}_furn,\n "sourceImage": {v}_src\n}}'
    ts.append(js+',')
ts.append('];')
open(f'{OUT}/data/plans.generated.ts','w').write('\n'.join(ts))
